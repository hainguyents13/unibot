import type { ItemContent } from "./transcript";

const PROCESS_PREFIX = "[IMPORTANT: Background process ";
const DELEGATION_PREFIX = "[ASYNC DELEGATION";
/** What Hermes appends for the model. Its reader only needs what happened. */
const FOOTER = "[INTERNAL NOTIFICATION — generated by the Hermes gateway";
const HELPER_FINISHED = "A background helper finished";

/**
 * How a user row reads in a chat. Hermes stores turns it starts itself as user messages so the
 * model reads them, marked with a display kind, but nobody typed them. Rows saved before Hermes typed
 * them have only their wording to go on. An unknown kind stays a message, so nothing you wrote can
 * disappear.
 */
export function gatewayTurnContent(text: string, kind?: string, title?: string): ItemContent {
  const body = withoutFooter(text);
  if (kind === "process_complete" || body.startsWith(PROCESS_PREFIX)) {
    const [headline, detail] = firstLine(unwrapped(body));
    return { kind: "result", title: title ?? headline, detail };
  }
  if (kind === "async_delegation_complete" || body.startsWith(DELEGATION_PREFIX)) {
    return { kind: "result", title: title ?? HELPER_FINISHED, detail: firstLine(body)[1] };
  }
  if (kind === "internal_notification") return { kind: "result", title: title ?? "Message from Hermes", detail: body };
  if (kind === "auto_continue") return { kind: "notice", text: "Picked up an interrupted reply" };
  return { kind: "user", text };
}

/** What the sidebar says when one of these is the chat's newest message. */
export function gatewayTurnPreview(text: string): string | undefined {
  if (text.startsWith(PROCESS_PREFIX)) return "Background process finished";
  if (text.startsWith(DELEGATION_PREFIX)) return HELPER_FINISHED;
  return undefined;
}

function withoutFooter(text: string): string {
  const at = text.lastIndexOf(FOOTER);
  return (at >= 0 ? text.slice(0, at) : text).trim();
}

/** `[IMPORTANT: …]` without its brackets. */
function unwrapped(text: string): string {
  let body = text;
  if (body.startsWith("[IMPORTANT: ")) body = body.slice("[IMPORTANT: ".length);
  if (body.endsWith("]")) body = body.slice(0, -1);
  return body.trim();
}

function firstLine(text: string): [string, string] {
  const at = text.indexOf("\n");
  return at < 0 ? [text, ""] : [text.slice(0, at), text.slice(at + 1).trim()];
}
